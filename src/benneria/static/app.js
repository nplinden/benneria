const $ = (s) => document.querySelector(s);
const out = $("#out");
let lastResults = [];

// ---------- helpers ----------
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, c =>
  ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
// Tag with an optional label. Values come from the lexicon database and are escaped.
function chip(label, value) {
  if (value === undefined || value === null || value === "" || value === false) return "";
  return `<span class="chip">${label ? `<b>${esc(label)}</b> ` : ""}${esc(String(value))}</span>`;
}

// OSIS verse id to a short reference: "Neh.12.45" -> "Neh 12:45".
const verseLabel = (v) => v.replace(/^(\w+)\.(\d+)\.(\d+)$/, "$1 $2:$3");
const entryLink = (r) => `<a data-entry="${esc(r.id)}" href="#" class="he">${esc(r.headword)}</a>`;

// One dictionary entry. Its BDB and Strong's HTML is generated by scripts/build_data.py from
// escaped XML text and a fixed set of tags, so it is inserted as is.
function renderEntry(e) {
  const s = e.strongs || {};
  const meta = [
    chip("", s.pos ? morphName(s.pos) : posName(e.pos)),
    chip("", langName(e.lang)),
    chip("Strong's", e.strong && /^\d/.test(e.strong) ? e.strong + (e.aug || "") : ""),
    chip("TWOT", e.twot),
    chip("BDB p.", e.bdb && e.bdb.page),
    chip("Occurrences", e.count || ""),
  ].join("");

  const forms = e.matches.length ? `<div class="forms"><b>Found as</b> ${e.matches.map(m =>
    `<span class="form${m.in_ref ? " in-ref" : ""}"><span class="he" dir="rtl">${esc(m.form)}</span>
      <span class="parse" title="morphhb parse: ${esc(m.morph)}">${esc(parseName(m.morph))}</span>${m.variant ? ` <i>${esc(m.variant)}</i>` : ""}
      ×${m.count} <small>${esc(m.refs.map(verseLabel).join(", "))}${m.count > m.refs.length ? "…" : ""}</small></span>`
  ).join("")}</div>` : "";

  let body = "";
  if (s.meaning_html) body += `<div>${s.meaning_html}</div>`;
  if (s.usage_html) body += `<div class="note"><b>Usage:</b> ${s.usage_html}</div>`;
  if (s.source_html) body += `<div class="note"><b>Source:</b> ${s.source_html}</div>`;
  if (e.bdb) body += `<details class="bdb"><summary>Brown-Driver-Briggs</summary>${e.bdb.html}</details>`;

  const related = e.related.length ? `<div class="refs">${e.related[0].relation === "origin" ? "From" : "Derivatives"}: ${
    e.related.map(r => `${entryLink(r)}${r.gloss ? ` <small>${esc(r.gloss)}</small>` : ""}`).join(" · ")}</div>` : "";
  const nav = `<div class="nav"><span>${e.prev ? "← " + entryLink(e.prev) : ""}</span>
    <span>${e.next ? entryLink(e.next) + " →" : ""}</span></div>`;

  return `<article class="entry">
    <div class="entry-head">
      <div class="hw" dir="rtl">${esc(e.headword)}${e.bdb && e.bdb.homonym ? ` <small>${esc(e.bdb.homonym)}</small>` : ""}</div>
      <div class="lex">${esc(e.gloss || "")}</div>
    </div>
    ${meta ? `<div class="meta">${meta}</div>` : ""}
    ${forms}${body || `<div class="note">No definition text in this entry.</div>`}
    ${related}${nav}
  </article>`;
}

// ---------- filters ----------
// These run in the browser on the returned entries; they never change the request.
// Choices persist across searches until the page is reloaded; everything is shown by default.
const langChoice = new Map();  // "Hebrew" / "Aramaic" -> shown?
const posChoice = new Map();   // Lexical Index part-of-speech code -> shown?

const entryLang = (e) => e.lang === "arc" ? "Aramaic" : "Hebrew";
const entryPos = (e) => e.pos || "";
const langShown = (l) => langChoice.get(l) ?? true;
const posShown = (p) => posChoice.get(p) ?? true;
const entryShown = (e) => langShown(entryLang(e)) && posShown(entryPos(e));

function countBy(items, key) {
  const m = new Map();
  items.forEach(x => m.set(key(x), (m.get(key(x)) || 0) + 1));
  return m;
}

function renderFilters() {
  const has = lastResults.length > 0;
  $("#filtersEmpty").hidden = has;
  $("#langRow").hidden = !has;
  $("#langFilters").innerHTML = [...countBy(lastResults, entryLang)].map(([l, n]) =>
    `<label><input type="checkbox" data-lang="${esc(l)}" ${langShown(l) ? "checked" : ""}> ${esc(l)} (${n})</label>`
  ).join("");
  const parts = countBy(lastResults, entryPos);
  $("#posRow").hidden = !parts.size;
  $("#posFilters").innerHTML = [...parts].sort((a, b) => b[1] - a[1]).map(([p, n]) =>
    `<label title="${esc(p || "no part of speech given")}"><input type="checkbox" data-pos="${esc(p)}" ${posShown(p) ? "checked" : ""}> ${esc(p ? posName(p) : "No part of speech")} (${n})</label>`
  ).join("");
}
$("#filterGroup").addEventListener("change", (ev) => {
  const d = ev.target.dataset;
  if (d.lang !== undefined) langChoice.set(d.lang, ev.target.checked);
  else if (d.pos !== undefined) posChoice.set(d.pos, ev.target.checked);
  else return;
  renderFilters();
  renderResults();
});

function renderResults() {
  const shown = lastResults.filter(entryShown);
  $("#optsCount").textContent = lastResults.length ? ` · showing ${shown.length} of ${lastResults.length} entries` : "";
  out.innerHTML = shown.map(renderEntry).join("") ||
    `<div class="status">No entries match the result filters. Adjust them under Options.</div>`;
}

// ---------- history ----------
// The storage key predates the rename to Benneria; kept so existing history survives.
function getHistory() { try { return JSON.parse(localStorage.getItem("sefaria-dict-history") || "[]"); } catch { return []; } }
function pushHistory(w) {
  const h = [w, ...getHistory().filter(x => x !== w)].slice(0, 12);
  try { localStorage.setItem("sefaria-dict-history", JSON.stringify(h)); } catch {}
  renderHistory();
}
function renderHistory() {
  const h = getHistory();
  $("#history").innerHTML = h.length ? "Recent: " + h.map(w => `<a data-word="${esc(w)}">${esc(w)}</a>`).join("") : "";
}

// ---------- search ----------
const SEARCH_OPTIONS = ["lookup_ref", "always_consonants", "always_split", "never_split", "strip_prefixes"];
const OPEN_KEYS = ["id", "bdb", "strong"];  // cross-references: /api/entry?id=, ?bdb=, ?strong=

async function lookup(word, push = true) {
  word = word.trim();
  if (!word) return;
  $("#q").value = word;
  const params = new URLSearchParams({ word });
  for (const k of SEARCH_OPTIONS) {
    const v = document.getElementById(k).value.trim();
    if (v) params.set(k, v);
  }
  if (push) history.pushState({ word }, "", "?" + params.toString());
  const ok = await fetchResults("/api/lookup?" + params.toString(), `No dictionary entries found for
    <span class="he">${esc(word)}</span>. Try turning on “Ignore vowels” or “Look up each word”.`);
  if (ok) pushHistory(word);
}

// Opens entries named by a cross-reference (an entry id, BDB id or Strong's number).
async function openEntry(kind, value, push = true) {
  const params = new URLSearchParams({ [kind]: value });
  if (push) history.pushState({ [kind]: value }, "", "?" + params.toString());
  await fetchResults("/api/entry?" + params.toString(), "No entry found for this reference.");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

async function fetchResults(url, emptyMessage) {
  out.innerHTML = `<div class="status">Searching…</div>`;
  lastResults = [];
  renderFilters();
  $("#optsCount").textContent = "";
  try {
    const r = await fetch(url);
    const data = await r.json();
    if (!r.ok || data.error) throw new Error(data.error || `HTTP ${r.status}`);
    lastResults = data.results || [];
    if (!lastResults.length) {
      out.innerHTML = `<div class="status">${emptyMessage}</div>`;
      return true;
    }
    renderFilters();
    renderResults();
    return true;
  } catch (err) {
    out.innerHTML = `<div class="status error">${esc(err.message)}</div>`;
    return false;
  }
}

$("#f").addEventListener("submit", (ev) => { ev.preventDefault(); lookup($("#q").value); });
$("#apiGroup").addEventListener("change", () => { if ($("#q").value.trim()) lookup($("#q").value); });
document.addEventListener("click", (ev) => {
  const a = ev.target.closest("[data-word]");
  if (a) { ev.preventDefault(); lookup(a.dataset.word); window.scrollTo({ top: 0, behavior: "smooth" }); return; }
  // Cross-references inside entries: related entries, BDB and Strong's links.
  const x = ev.target.closest("[data-entry], [data-bdb], [data-strong]");
  if (x) {
    ev.preventDefault();
    const d = x.dataset;
    if (d.entry) openEntry("id", d.entry);
    else if (d.bdb) openEntry("bdb", d.bdb);
    else openEntry("strong", d.strong);
  }
});
function route(push) {
  const p = new URLSearchParams(location.search);
  const kind = OPEN_KEYS.find(k => p.get(k));
  if (kind) openEntry(kind, p.get(kind), push);
  else if (p.get("word")) lookup(p.get("word"), push);
  else showWelcome();
}
window.addEventListener("popstate", () => route(false));

function showWelcome() {
  lastResults = [];
  $("#q").value = "";
  renderFilters();
  $("#optsCount").textContent = "";
  out.innerHTML = `<div class="status">Enter a Hebrew or Aramaic word to search the dictionaries.<br>
    Try ${["תורה","שלום","ראה","אמר"].map(w => `<a data-word="${w}" href="#" class="he">${w}</a>`).join(" · ")}</div>`;
}

