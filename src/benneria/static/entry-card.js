// Renders one dictionary entry as a card: Strong's and BDB side by side under one headword.
// Shared by the dictionary (app.js) and the statistics page (benneria_stats/static/stats.js),
// so a root's definition looks the same wherever it's shown. Needs labels.js (morphName,
// posName, langName) to be loaded first.

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, c =>
  ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
// Tag with an optional label. Values come from the lexicon database and are escaped.
function chip(label, value) {
  if (value === undefined || value === null || value === "" || value === false) return "";
  return `<span class="chip">${label ? `<b>${esc(label)}</b> ` : ""}${esc(String(value))}</span>`;
}

const entryLink = (r) => `<a data-entry="${esc(r.id)}" href="#" class="he">${esc(r.headword)}</a>`;

// One dictionary entry. Its BDB and Strong's HTML is generated by scripts/build_data.py from
// escaped XML text and a fixed set of tags, so it is inserted as is.
// With bdbOnly (the statistics page's definitions), only the BDB section is shown, with no
// meta pills (part of speech, language, Strong's #, BDB p.#) above it.
function renderEntry(e, { bdbOnly = false } = {}) {
  const s = e.strongs || {};
  const meta = bdbOnly ? "" : [
    chip("", s.pos ? morphName(s.pos) : posName(e.pos)),
    chip("", langName(e.lang)),
    chip("Strong's", e.strong && /^\d/.test(e.strong) ? e.strong + (e.aug || "") : ""),
    chip("BDB p.", e.bdb && e.bdb.page),
  ].join("");

  // Strong's and BDB, both shown in full, each under its own heading.
  let strongs = "";
  if (!bdbOnly) {
    if (s.meaning_html) strongs += `<div>${s.meaning_html}</div>`;
    if (s.usage_html) strongs += `<div class="field"><b>Usage:</b> ${s.usage_html}</div>`;
    if (s.source_html) strongs += `<div class="field"><b>Source:</b> ${s.source_html}</div>`;
  }
  let body = "";
  if (strongs) body += `<section class="source strongs"><h4>Strong's</h4>${strongs}</section>`;
  if (e.bdb) body += `<section class="source bdb"><h4>Brown-Driver-Briggs</h4>${e.bdb.html}</section>`;

  const related = e.related.length ? `<div class="refs">${e.related[0].relation === "origin" ? "From" : "Derivatives"}: ${
    e.related.map(r => `${entryLink(r)}${r.gloss ? ` <small>${esc(r.gloss)}</small>` : ""}`).join(" · ")}</div>` : "";

  return `<article class="entry">
    <div class="entry-head">
      <div class="hw" dir="rtl">${esc(e.headword)}${e.bdb && e.bdb.homonym ? ` <small>${esc(e.bdb.homonym)}</small>` : ""}</div>
    </div>
    ${meta ? `<div class="meta">${meta}</div>` : ""}
    ${body || `<div class="note">No definition text in this entry.</div>`}
    ${related}
  </article>`;
}
